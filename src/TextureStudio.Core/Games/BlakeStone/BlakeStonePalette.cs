    /// <summary>RGBA8888 palette; index 0xFF is the transparent color key for sprites.</summary>
    public static uint[] ToRgba()
    {
        var pal = new uint[256];
        for (var i = 0; i < 256; i++)
        {
            var r = (byte)((Raw6Bit[i * 3 + 0] * 255 + 31) / 63);
            var g = (byte)((Raw6Bit[i * 3 + 1] * 255 + 31) / 63);
            var b = (byte)((Raw6Bit[i * 3 + 2] * 255 + 31) / 63);
            pal[i] = (uint)(r | (g << 8) | (b << 16) | (0xFFu << 24));
        }
        return pal;
    }
